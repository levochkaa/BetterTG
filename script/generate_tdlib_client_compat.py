#!/usr/bin/env python3
"""Generate native TDClient conveniences for calls used by BetterTG."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SCHEMA = ROOT.parent.parent / "Sources/TDLibKitNative/Generated/SchemaViews.swift"
OUTPUT = ROOT / "BetterTG/Shared/TDClient+Generated.swift"
SOURCE_ROOTS = (ROOT / "BetterTG", ROOT / "BetterTGNotificationService")

REQUEST = re.compile(
    r"^    public static func ([A-Za-z][A-Za-z0-9]*)\((.*)\) -> TDRequest<([^>]+)> \{$",
    re.MULTILINE,
)
# What ReadmeDemo answers itself, through TDClientDemoResponses, in Debug builds.
DEMO_REQUESTS = {
    "closeChat", "createPrivateChat", "downloadFile", "getBasicGroup", "getBasicGroupFullInfo", "getChat",
    "getChatHistory", "getChatMessageCount", "getChatPinnedMessage", "getChats", "getFile", "getMe", "getMessage",
    "getMessageAvailableReactions", "getMessageProperties", "getMessages", "getRepliedMessage", "getSupergroup", "getSupergroupFullInfo",
    "getTopChats", "getUser", "getUserFullInfo", "getUserProfilePhotos", "openChat", "searchChatMessages",
    "searchChats", "searchRecentlyFoundChats", "viewMessages",
}
CLIENT_CALL = re.compile(
    r"\b(?:td|client|callbackClient)\.([a-z][A-Za-z0-9]*)\s*\("
)


def split_parameters(parameters: str) -> list[str]:
    if not parameters:
        return []
    result: list[str] = []
    start = 0
    depth = 0
    for index, character in enumerate(parameters):
        if character in "[(<{":
            depth += 1
        elif character in ")]>}":
            depth -= 1
        elif character == "," and depth == 0:
            result.append(parameters[start:index].strip())
            start = index + 1
    result.append(parameters[start:].strip())
    return result


def argument(parameter: str) -> str:
    name = parameter.split(":", maxsplit=1)[0].strip()
    local_name = name.split()[-1]
    if name.startswith("_ "):
        return local_name
    return f"{name.strip('`')}: {local_name}"


def call_argument_text(source: str, open_parenthesis: int) -> str | None:
    depth = 1
    quote: str | None = None
    escaped = False
    for index in range(open_parenthesis + 1, len(source)):
        character = source[index]
        if quote is not None:
            if escaped:
                escaped = False
            elif character == "\\":
                escaped = True
            elif character == quote:
                quote = None
            continue
        if character in {'"', "'"}:
            quote = character
        elif character == "(":
            depth += 1
        elif character == ")":
            depth -= 1
            if depth == 0:
                return source[open_parenthesis + 1 : index]
    return None


def observed_calls(source: str) -> list[tuple[str, tuple[str, ...]]]:
    result: list[tuple[str, tuple[str, ...]]] = []
    for match in CLIENT_CALL.finditer(source):
        arguments = call_argument_text(source, match.end() - 1)
        if arguments is None:
            continue
        labels: list[str] = []
        for item in split_parameters(arguments):
            label = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*):", item)
            if label:
                labels.append(label.group(1))
        result.append((match.group(1), tuple(labels)))
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    args = parser.parse_args()

    schema = args.schema.read_text()
    requests = {
        name: (parameters, response)
        for name, parameters, response in REQUEST.findall(schema)
    }
    used: set[str] = set()
    observed_orders: dict[str, set[tuple[str, ...]]] = {}
    for source_root in SOURCE_ROOTS:
        for source in source_root.rglob("*.swift"):
            if source == OUTPUT:
                continue
            for name, order in observed_calls(source.read_text()):
                used.add(name)
                observed_orders.setdefault(name, set()).add(order)

    selected = sorted((set(requests) & used) - {"close"})
    missing = sorted(used - set(requests) - {
        "close", "decoder", "getOption", "setLogStream", "setTdlibParameters"
    })
    lines = [
        "// Generated by script/generate_tdlib_client_compat.py. Do not edit.\n",
        "// Every convenience sends a typed native TDRequest; no JSON is involved.\n\n",
        "import Foundation\n",
        "import TDLibKit\n\n",
        "extension TDClient {\n",
    ]
    for name in selected:
        parameters, response = requests[name]
        canonical = split_parameters(parameters)
        canonical_names = tuple(item.split(":", maxsplit=1)[0].strip().strip("`") for item in canonical)
        parameters_by_name = {
            item.split(":", maxsplit=1)[0].strip().strip("`"): item
            for item in canonical
        }
        orders = {
            order
            for order in observed_orders.get(name, set())
            if len(order) == len(canonical_names) and set(order) == set(canonical_names)
        }
        if not orders:
            orders = {canonical_names}
        arguments = ", ".join(argument(item) for item in canonical)
        for order in sorted(orders):
            ordered_parameters = ", ".join(parameters_by_name[label] for label in order)
            lines.append(f"    func {name}({ordered_parameters}) async throws -> {response} {{\n")
            if name in DEMO_REQUESTS:
                demo_arguments = ", ".join(f'"{label}": {label} as Any' for label in canonical_names) or ":"
                lines.extend(
                    [
                        "        #if DEBUG\n",
                        f'        if let demo = TDClientDemoResponses.answer?("{name}", [{demo_arguments}]) as? {response} {{\n',
                        "            return demo\n",
                        "        }\n",
                        "        #endif\n",
                        f"        return try await send(TDNativeRequests.{name}({arguments}))\n",
                    ]
                )
            else:
                lines.append(f"        try await send(TDNativeRequests.{name}({arguments}))\n")
            lines.append("    }\n\n")
    lines.append("}\n")
    output = "".join(lines)
    if not OUTPUT.exists() or OUTPUT.read_text() != output:
        OUTPUT.write_text(output)
        print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(selected)} requests)")
    else:
        print(f"Kept {OUTPUT.relative_to(ROOT)} unchanged ({len(selected)} requests)")
    if missing:
        print("Non-request TDClient members: " + ", ".join(missing))


if __name__ == "__main__":
    main()
