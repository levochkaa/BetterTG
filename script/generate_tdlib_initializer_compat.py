#!/usr/bin/env python3
"""Generate source-order initializer shims over zero-copy native views."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from generate_tdlib_client_compat import argument, call_argument_text, split_parameters


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SCHEMA = ROOT.parent.parent / "Sources/TDLibKitNative/Generated/SchemaViews.swift"
OUTPUT = ROOT / "BetterTG/Shared/TDNativeInitializers+Generated.swift"
SOURCE_ROOTS = (ROOT / "BetterTG", ROOT / "BetterTGNotificationService")
STRUCT = re.compile(r"^public struct TDNative([A-Za-z][A-Za-z0-9]*):")
INITIALIZER = re.compile(r"^    public init\((.*)\) \{$")
EXPLICIT_CALL = re.compile(r"\b([A-Z][A-Za-z0-9]*)\s*\(")


def canonical_initializers(schema: str) -> dict[str, str]:
    result: dict[str, str] = {}
    current: str | None = None
    for line in schema.splitlines():
        if match := STRUCT.match(line):
            current = match.group(1)
            continue
        if current is not None and (match := INITIALIZER.match(line)):
            result[current] = match.group(1)
    return result


def observed_orders(source: str, known: set[str]) -> list[tuple[str, tuple[str, ...]]]:
    result: list[tuple[str, tuple[str, ...]]] = []
    for match in EXPLICIT_CALL.finditer(source):
        name = match.group(1)
        if name not in known:
            continue
        arguments = call_argument_text(source, match.end() - 1)
        if arguments is None:
            continue
        labels: list[str] = []
        for item in split_parameters(arguments):
            label = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*):", item)
            if label:
                labels.append(label.group(1))
        result.append((name, tuple(labels)))
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    args = parser.parse_args()

    canonical = canonical_initializers(args.schema.read_text())
    orders: dict[str, set[tuple[str, ...]]] = {}
    for source_root in SOURCE_ROOTS:
        for source in source_root.rglob("*.swift"):
            if source == OUTPUT:
                continue
            for name, order in observed_orders(source.read_text(), set(canonical)):
                orders.setdefault(name, set()).add(order)

    shims: list[tuple[str, tuple[str, ...]]] = []
    for name, observed in orders.items():
        parameters = split_parameters(canonical[name])
        canonical_names = tuple(
            item.split(":", maxsplit=1)[0].strip().strip("`") for item in parameters
        )
        for order in observed:
            if (
                order != canonical_names
                and len(order) == len(canonical_names)
                and set(order) == set(canonical_names)
            ):
                shims.append((name, order))

    lines = [
        "// Generated by script/generate_tdlib_initializer_compat.py. Do not edit.\n",
        "// These reorder source labels only; storage remains native and zero-copy.\n\n",
        "import Foundation\n",
        "import TDLibKit\n\n",
    ]
    for name, order in sorted(shims):
        parameters = split_parameters(canonical[name])
        by_name = {
            item.split(":", maxsplit=1)[0].strip().strip("`"): item
            for item in parameters
        }
        ordered = ", ".join(by_name[label] for label in order)
        forwarded = ", ".join(argument(item) for item in parameters)
        lines.extend(
            [
                f"extension TDNative{name} {{\n",
                f"    init({ordered}) {{\n",
                f"        self.init({forwarded})\n",
                "    }\n",
                "}\n\n",
            ]
        )
    output = "".join(lines)
    if not OUTPUT.exists() or OUTPUT.read_text() != output:
        OUTPUT.write_text(output)
        print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(shims)} shims)")
    else:
        print(f"Kept {OUTPUT.relative_to(ROOT)} unchanged ({len(shims)} shims)")


if __name__ == "__main__":
    main()
