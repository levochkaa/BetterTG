#!/usr/bin/env python3
"""Generate zero-copy source aliases for BetterTG's TDLibKit 1 model names."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SCHEMA = ROOT.parent.parent / "Sources/TDLibKitNative/Generated/SchemaViews.swift"
OUTPUT = ROOT / "BetterTG/Shared/TDNativeAliases.swift"
SOURCE_ROOTS = (ROOT / "BetterTG", ROOT / "BetterTGNotificationService")

DECLARATION = re.compile(
    r"^public (?:struct|enum|protocol) TDNative([A-Za-z][A-Za-z0-9]*)\b",
    re.MULTILINE,
)
IDENTIFIER = re.compile(r"\b[A-Za-z][A-Za-z0-9]*\b")
LOCAL_TYPE = re.compile(
    r"^(?:(?:public|internal|private|fileprivate|final|@MainActor)\s+)*"
    r"(?:struct|enum|class|actor|protocol)\s+([A-Za-z][A-Za-z0-9]*)\b",
    re.MULTILINE,
)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    args = parser.parse_args()

    schema = args.schema.read_text()
    available = set(DECLARATION.findall(schema))
    used: set[str] = set()
    local_types: set[str] = set()
    for source_root in SOURCE_ROOTS:
        for source in source_root.rglob("*.swift"):
            if source == OUTPUT:
                continue
            text = source.read_text()
            used.update(IDENTIFIER.findall(text))
            local_types.update(LOCAL_TYPE.findall(text))

    # Swift.Error remains the unqualified error protocol throughout BetterTG.
    selected = sorted(
        (available & used) - local_types - {"Data", "Date", "Error", "Notification", "PhoneNumberInfo"}
    )
    lines = [
        "// Generated by script/generate_tdlib_native_aliases.py. Do not edit.\n",
        "// Aliases preserve native object ownership; they do not copy model graphs.\n\n",
        "import TDLibKit\n\n",
        "public typealias TDLibClient = TDClient\n",
    ]
    lines.extend(f"public typealias {name} = TDNative{name}\n" for name in selected)
    output = "".join(lines)
    if not OUTPUT.exists() or OUTPUT.read_text() != output:
        OUTPUT.write_text(output)
        print(f"Generated {OUTPUT.relative_to(ROOT)} ({len(selected)} aliases)")
    else:
        print(f"Kept {OUTPUT.relative_to(ROOT)} unchanged ({len(selected)} aliases)")


if __name__ == "__main__":
    main()
