import { createHash } from 'node:crypto'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const sourceUrl = 'https://core.telegram.org/api/config.json'
const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const backendRoot = resolve(scriptDirectory, '..')
const repositoryRoot = resolve(backendRoot, '..')
const generatedCatalogPath = resolve(
    backendRoot,
    'src/telegram-web-push/classification/telegram-push-catalog.generated.ts',
)
const stringsPath = resolve(repositoryRoot, 'BetterTG/Resources/en.lproj/Localizable.strings')

const serviceOrUnsupportedKeys = new Set(['DC_UPDATE', 'PHONE_CALL_REQUEST'])

const response = await fetch(sourceUrl)
if (!response.ok) throw new Error(`Telegram push catalog request failed: ${response.status}`)
const sourceText = await response.text()
const config = JSON.parse(sourceText)
if (!config.push || typeof config.push !== 'object') {
    throw new Error('Telegram config does not contain a push catalog')
}

const templates = Object.entries(config.push)
    .filter(
        ([key, value]) =>
            /^[A-Z0-9_]+$/.test(key) &&
            typeof value === 'string' &&
            !serviceOrUnsupportedKeys.has(key),
    )
    .sort(([left], [right]) => left.localeCompare(right))
const argumentCounts = Object.fromEntries(
    templates.map(([key]) => [key, Object.keys(config.push_arguments?.[key] ?? {}).length]),
)
const sourceHash = createHash('sha256').update(sourceText).digest('hex')

const generatedCatalog = `// Generated by scripts/update-telegram-push-catalog.mjs. Do not edit manually.
// Source: ${sourceUrl}

export const TELEGRAM_PUSH_CATALOG_SHA256 = '${sourceHash}'

export const TELEGRAM_VISIBLE_PUSH_KEYS: ReadonlySet<string> = new Set(${JSON.stringify(
    templates.map(([key]) => key),
    null,
    4,
)})

export const TELEGRAM_PUSH_ARGUMENT_COUNTS: Readonly<Record<string, number>> = ${JSON.stringify(
    argumentCounts,
    null,
    4,
)}
`

function appleFormat(template) {
    return template.replaceAll('%', '%%').replace(/\{(\d+)\}/g, (_, index) => `%${index}$@`)
}

const strings = [
    '// Generated by Backend/scripts/update-telegram-push-catalog.mjs. Do not edit manually.',
    ...templates.map(
        ([key, template]) => `${JSON.stringify(key)} = ${JSON.stringify(appleFormat(template))};`,
    ),
    '',
].join('\n')

await mkdir(dirname(generatedCatalogPath), { recursive: true })
await mkdir(dirname(stringsPath), { recursive: true })
await writeFile(generatedCatalogPath, generatedCatalog)
await writeFile(stringsPath, strings)

console.log(`Generated ${templates.length} visible Telegram push localizations`)
